-- Buat bucket publik untuk video.
insert into storage.buckets (id, name, public)
values ('videos', 'videos', true)
on conflict (id) do update set public = true;

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  public_url text not null,
  storage_path text not null,
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.videos enable row level security;

-- Siapa pun boleh membaca metadata video agar link publik dapat dibuka.
drop policy if exists "Public can read videos" on public.videos;
create policy "Public can read videos" on public.videos
for select to anon, authenticated using (true);

-- Hanya admin yang login boleh menambahkan dan menghapus metadata.
drop policy if exists "Authenticated can add own videos" on public.videos;
create policy "Authenticated can add own videos" on public.videos
for insert to authenticated with check (auth.uid() = owner_id);

drop policy if exists "Owner can delete own videos" on public.videos;
create policy "Owner can delete own videos" on public.videos
for delete to authenticated using (auth.uid() = owner_id);

-- Hanya pengguna yang login boleh mengunggah ke folder dengan nama user ID sendiri.
drop policy if exists "Authenticated upload own folder" on storage.objects;
create policy "Authenticated upload own folder" on storage.objects
for insert to authenticated
with check (bucket_id = 'videos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Authenticated delete own folder" on storage.objects;
create policy "Authenticated delete own folder" on storage.objects
for delete to authenticated
using (bucket_id = 'videos' and (storage.foldername(name))[1] = auth.uid()::text);

